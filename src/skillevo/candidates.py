"""Skill candidate generation from stored experiences. Deterministic templates; an LLM is never required."""

from __future__ import annotations

import json
import math
from collections import Counter
from dataclasses import dataclass

from . import redact, skills, tokenize
from .config import Config
from .store import Store

KINDS = ("lesson", "pattern", "workflow")


@dataclass
class Spec:
    name: str
    text: str
    evidence: list[int]
    reason: str
    sessions: int = 0


def yaml_quote(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ") + '"'


def _vec(row) -> set[str]:
    return set(row["index_text"].split())


def _cos(a: set[str], b: set[str]) -> float:
    return len(a & b) / math.sqrt(len(a) * len(b)) if a and b else 0.0


def cluster(rows: list, threshold: float = 0.3) -> list[list]:
    clusters: list[list] = []
    for r in rows:
        v = _vec(r)
        for c in clusters:
            if any(_cos(v, _vec(m)) >= threshold for m in c):
                c.append(r)
                break
        else:
            clusters.append([r])
    return clusters


def top_terms(rows: list, n: int = 3) -> list[str]:
    counts: Counter[str] = Counter()
    for r in rows:
        for t in set(tokenize.tokens(r["title"] + " " + " ".join(r["tags"].split(",")))):
            if len(t) >= 3 and t.isascii() and t.isalnum():
                counts[t] += 1
    return [t for t, _ in sorted(counts.items(), key=lambda kv: (-kv[1], kv[0]))[:n]]


def build_text(name: str, rows: list, terms: list[str]) -> str:
    topic = ", ".join(terms) if terms else "recurring tasks"
    first = redact.sanitize_for_injection(rows[0]["title"])[:100]
    desc = (f"Use when working on {topic} tasks. Applies {len(rows)} lesson(s) learned from earlier sessions, "
            f"for example: {first}.")
    lines = [
        "---", f"name: {name}", f"description: {yaml_quote(desc)}", "---", "",
        f"# {name}", "",
        "Lessons learned from earlier sessions, generated by SkillEvo. Review them before relying on them; "
        "edit this file freely (SkillEvo stops auto-editing a skill once you change it).", "",
        "## When to apply", f"- Tasks involving: {topic}", "", "## Lessons",
    ]
    for r in rows:
        body = redact.sanitize_for_injection(r["body"])
        lines.append(f"- {body} _(evidence #{r['id']})_")
    return "\n".join(lines) + "\n"


def generate(store: Store, cfg: Config, project: str, covered: set[int]) -> list[Spec]:
    rows = [r for kind in KINDS for r in store.list_experiences(project, "active", kind)]
    rows = [r for r in rows if r["id"] not in covered]
    rows.sort(key=lambda r: r["id"])
    specs: list[Spec] = []
    for members in cluster(rows):
        strong = max(m["salience"] for m in members) >= cfg.detection.candidate_salience
        if len(members) < cfg.detection.min_cluster_size and not strong:
            continue
        terms = top_terms(members)
        base = skills.slug("-".join(terms) if terms else f"lessons-{members[0]['id']}")
        name = skills.slug(cfg.skills.name_prefix + base)
        reason = (f"{len(members)} related experiences" if len(members) >= cfg.detection.min_cluster_size
                  else "single high-impact lesson")
        distinct = {s for m in members for s in m["sessions"].split(",") if s}
        specs.append(Spec(name, build_text(name, members, terms), [m["id"] for m in members], reason, len(distinct)))
    return specs


def evidence_terms(store: Store, ids: list[int], limit: int = 12) -> list[str]:
    counts: Counter[str] = Counter()
    for i in ids:
        row = store.get_experience(i)
        if row:
            counts.update(set(t for t in row["index_text"].split() if len(t) >= 4 and t.isascii()))
    return [t for t, _ in counts.most_common(limit)]


def parse_evidence(raw: str) -> list[int]:
    try:
        return [int(x) for x in json.loads(raw)]
    except (ValueError, TypeError):
        return []
